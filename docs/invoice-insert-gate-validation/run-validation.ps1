param()
$ErrorActionPreference = 'Stop'
$root = $PSScriptRoot
$image = 'postgres@sha256:2d2b8998d31037bf721cfdf764d76ba74171b4fab3431b7f72c27c56ddbdf9e3'
$container = 'microassist-gate-validation-' + [guid]::NewGuid().ToString('N').Substring(0,12)
$expectedHashes = @{
  'gate-proposal.sql'='4CF51AA8D0E484863637EB3CD09721C49B9A9D834D56DDC1F07F9027DFAA5187'
  'isolated-validation.sql'='AAD26A3CB419E54A46C5D6207E889C41E1E278B2B5C59574BE3998C2EDC50B2F'
  'invoices-schema-compatibility.sql'='28B48707D751BEF86744E6CF53758F90D26CE478F0220F9BDC526E937975A5EF'
}
$log = Join-Path $root 'execution.txt'
$records = [ordered]@{ startedUtc=[DateTime]::UtcNow.ToString('o'); image=$image; container=$container; productionAccess=$false; clientSuitesRun=$false; copies=@(); success=$false; cleanupVerified=$false }
Set-Content -LiteralPath $log -Value 'Disposable PostgreSQL-only validation; synthetic data only.' -Encoding UTF8
function Invoke-LocalDocker {
  param([string[]]$Arguments)
  Add-Content -LiteralPath $log -Value ('docker ' + ($Arguments -join ' '))
  $previousPreference = $ErrorActionPreference
  $ErrorActionPreference = 'Continue'
  $output = & docker @Arguments 2>&1
  $code = $LASTEXITCODE
  $ErrorActionPreference = $previousPreference
  $output | ForEach-Object { Add-Content -LiteralPath $log -Value $_.ToString().TrimEnd() }
  if ($code -ne 0) { throw "Docker command failed ($code): $($Arguments -join ' ')" }
  return $output
}
try {
  # Cached digest only. --pull=never prevents installation/download.
  Invoke-LocalDocker -Arguments @('run','-d','--pull=never','--name',$container,'--label','microassist.validation=invoice-insert-gate','--network','none','--tmpfs','/var/lib/postgresql/data:rw,size=268435456','--memory','384m','--cpus','1','-e','POSTGRES_HOST_AUTH_METHOD=trust',$image) | Out-Null
  $inspection = (Invoke-LocalDocker -Arguments @('inspect',$container) | Out-String | ConvertFrom-Json)[0]
  if ($inspection.HostConfig.NetworkMode -ne 'none' -or $inspection.HostConfig.PortBindings.Count -gt 0 -or @($inspection.Mounts | Where-Object {$_.Type -ne 'tmpfs'}).Count -gt 0) { throw 'Isolation verification failed' }
  $records.isolation = @{ network=$inspection.HostConfig.NetworkMode; portBindings=$inspection.HostConfig.PortBindings; mounts=$inspection.Mounts; imageId=$inspection.Image; label=$inspection.Config.Labels.'microassist.validation' }
  # Identify target BEFORE any SQL command. No host/linked credentials are used.
  Write-Output "SQL TARGET: disposable container $container, network=none, Unix socket, database=postgres, synthetic-only"
  $records.version = (Invoke-LocalDocker -Arguments @('exec',$container,'postgres','--version') | Out-String).Trim()
  $ready = $false
  for($attempt=0;$attempt -lt 40;$attempt++) {
    & docker exec $container pg_isready -U postgres -d postgres *> $null
    if($LASTEXITCODE -eq 0){$ready=$true;break}; Start-Sleep -Milliseconds 250
  }
  if(!$ready){throw 'Disposable PostgreSQL not ready'}
  foreach($file in @('gate-proposal.sql','isolated-validation.sql','invoices-schema-compatibility.sql')) {
    $source = Join-Path $root ('inputs/' + $file)
    $before = (Get-FileHash -LiteralPath $source -Algorithm SHA256).Hash
    if($before -ne $expectedHashes[$file]){throw "Reviewed input hash mismatch: $file"}
    Invoke-LocalDocker -Arguments @('cp',$source,($container + ':/tmp/' + $file)) | Out-Null
    $after = ((Invoke-LocalDocker -Arguments @('exec',$container,'sha256sum',('/tmp/' + $file)) | Out-String).Trim() -split '\s+')[0].ToUpperInvariant()
    if($before -ne $after){throw "SQL copy mismatch: $file"}
    $records.copies += @{file=$file;sourceSha256=$before;containerSha256=$after}
  }
  $supplementPath = Join-Path $root 'supplemental-validation.sql'
  $supplementHash = (Get-FileHash -LiteralPath $supplementPath -Algorithm SHA256).Hash
  Invoke-LocalDocker -Arguments @('cp',$supplementPath,($container + ':/tmp/supplemental-validation.sql')) | Out-Null
  $supplementCopy = ((Invoke-LocalDocker -Arguments @('exec',$container,'sha256sum','/tmp/supplemental-validation.sql') | Out-String).Trim() -split '\s+')[0].ToUpperInvariant()
  if($supplementCopy -ne $supplementHash){throw 'Supplement copy hash mismatch'}
  $records.copies += @{file='supplemental-validation.sql';sourceSha256=$supplementHash;containerSha256=$supplementCopy}
  Invoke-LocalDocker -Arguments @('exec',$container,'timeout','60s','psql','-X','-U','postgres','-d','postgres','-v','ON_ERROR_STOP=1','-v','VERBOSITY=verbose','-f','/tmp/isolated-validation.sql') | Out-Null
  Invoke-LocalDocker -Arguments @('exec',$container,'timeout','30s','psql','-X','-U','postgres','-d','postgres','-v','ON_ERROR_STOP=1','-v','VERBOSITY=verbose','-f','/tmp/supplemental-validation.sql') | Out-Null
  $records.success=$true
} finally {
  # Remove ONLY the container name generated by this run, verified by its label.
  $existing = & docker ps -aq --filter ('name=^/' + $container + '$')
  if($existing) {
    $label = ((& docker inspect $container | Out-String | ConvertFrom-Json)[0]).Config.Labels.'microassist.validation'
    if($label -ne 'invoice-insert-gate'){throw 'Refusing cleanup: unexpected container label'}
    Invoke-LocalDocker -Arguments @('rm','-f',$container) | Out-Null
  }
  $left = & docker ps -aq --filter ('name=^/' + $container + '$')
  $records.cleanupVerified = !$left
  $records.finishedUtc=[DateTime]::UtcNow.ToString('o')
  $records | ConvertTo-Json -Depth 10 | Set-Content -LiteralPath (Join-Path $root 'results.json') -Encoding UTF8
}
if(!$records.success -or !$records.cleanupVerified){throw 'Validation or cleanup failed'}
Write-Output 'POSTGRES_ONLY_VALIDATION_PASSED; CLEANUP_VERIFIED'
